#!/usr/bin/env python3
"""Ship the runtime node_modules packages the vscode-web client loads from
`/node_modules/<pkg>/...` into the client directory.

Upstream's `gulp vscode-web` packaging does NOT include node_modules (the
official `code serve-web` npm package ships them separately). The web
workbench resolves these packages at runtime via FileAccess/nodeModulesPath
(see src/vs/base/common/network.ts consumers):

  - vscode-regexp-languagedetection   language detection worker (seen 404 in the field)
  - vscode-oniguruma                  textmate tokenizer (main.js + onig.wasm)
  - @vscode/tree-sitter-wasm          experimental tree-sitter highlighting
  - @vscode/vscode-languagedetection  ml language detection fallback

Usage: ship_node_modules.py <client_dir> <source_node_modules_dir>

The client's built JS is also scanned for additional `node_modules/<pkg>`
references so future upstream additions are picked up automatically.
"""
import os
import re
import shutil
import sys

KNOWN = [
    "vscode-regexp-languagedetection",
    "vscode-oniguruma",
    "@vscode/tree-sitter-wasm",
    "@vscode/vscode-languagedetection",
]

IGNORE = shutil.ignore_patterns("*.map", "node_modules", ".bin", "*.md", "test*", "coverage")


def main() -> None:
    if len(sys.argv) != 3:
        print("usage: ship_node_modules.py <client_dir> <source_node_modules_dir>")
        sys.exit(2)
    client_dir, src_node_modules = sys.argv[1], sys.argv[2]

    wanted = set(KNOWN)
    pattern = re.compile(r"node_modules/(@[A-Za-z0-9._-]+/[A-Za-z0-9._-]+|[A-Za-z0-9._-]+)")
    out_dir = os.path.join(client_dir, "out")
    if os.path.isdir(out_dir):
        for root, _dirs, files in os.walk(out_dir):
            for name in files:
                if not name.endswith((".js", ".html")):
                    continue
                try:
                    with open(os.path.join(root, name), encoding="utf-8", errors="ignore") as f:
                        text = f.read()
                except OSError:
                    continue
                wanted.update(pattern.findall(text))

    shipped = []
    for pkg in sorted(wanted):
        src = os.path.join(src_node_modules, pkg)
        if not os.path.isdir(src):
            # scanned references may include packages that only exist in
            # node/electron layers — warn, don't fail
            print(f"warn: {pkg} not in source node_modules - skipped")
            continue
        dest = os.path.join(client_dir, "node_modules", pkg)
        if os.path.isdir(dest):
            shutil.rmtree(dest)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.copytree(src, dest, ignore=IGNORE)
        shipped.append(pkg)
        print(f"ok  {pkg}")

    if not shipped:
        print("::warning::no node_modules packages shipped")
        sys.exit(1)

    # hard requirement: observed 404 for this file in the field
    req = os.path.join(
        client_dir, "node_modules", "vscode-regexp-languagedetection", "dist", "index.js"
    )
    if not os.path.isfile(req):
        print("::error::vscode-regexp-languagedetection/dist/index.js missing after ship")
        sys.exit(1)

    total = 0
    nm_dir = os.path.join(client_dir, "node_modules")
    for root, _dirs, files in os.walk(nm_dir):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                pass
    print(f"shipped {len(shipped)} packages, {total / (1024 * 1024):.1f} MB total")


if __name__ == "__main__":
    main()
